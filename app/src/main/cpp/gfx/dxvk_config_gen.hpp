#pragma once

#include <algorithm>
#include <cstdint>
#include <fstream>
#include <sstream>
#include <string>

namespace mobiro::gfx {

struct DxvkProfileParams {
    uint64_t total_ram_mb = 8192;
    int compiler_threads = 3;
    int max_frame_rate = 60;
    bool enable_hud = false;
};

struct DxvkMemoryBudget {
    uint64_t max_device_memory_mb = 4096;
    uint64_t max_shared_memory_mb = 2048;
    int max_chunk_size_mb = 64;
};

// Computes safe mobile UMA VRAM caps so Android's lmkd does not kill the process.
inline DxvkMemoryBudget compute_uma_budget(uint64_t total_ram_mb) {
    DxvkMemoryBudget b;
    // Target ~38% of physical RAM for device-local VRAM reporting, clamped to [2048, 6144] MB
    const uint64_t dev = std::clamp<uint64_t>((total_ram_mb * 38) / 100, 2048, 6144);
    const uint64_t shared = std::clamp<uint64_t>(dev / 2, 1024, 3072);
    b.max_device_memory_mb = dev;
    b.max_shared_memory_mb = shared;
    b.max_chunk_size_mb = (total_ram_mb >= 12288) ? 64 : 32;
    return b;
}

inline std::string render_dxvk_conf(const DxvkProfileParams& p) {
    const auto budget = compute_uma_budget(p.total_ram_mb);
    const int threads = std::clamp(p.compiler_threads, 1, 6);
    const int fps = std::clamp(p.max_frame_rate, 30, 60);

    std::ostringstream out;
    out << "# Auto-generated by Mobiro Runtime (Adreno + Mesa Turnip UMA Profile)\n"
        << "dxvk.enableGraphicsPipelineLibrary = True\n"
        << "dxvk.enableStateCache = True\n"
        << "dxvk.numCompilerThreads = " << threads << "\n"
        << "dxvk.maxChunkSize = " << budget.max_chunk_size_mb << "\n"
        << "dxvk.enableMemoryDefrag = True\n"
        << "dxgi.maxDeviceMemory = " << budget.max_device_memory_mb << "\n"
        << "dxgi.maxSharedMemory = " << budget.max_shared_memory_mb << "\n"
        << "d3d11.invariantPosition = True\n"
        << "d3d11.cachedDynamicResources = \"vi\"\n"
        << "d3d11.relaxedBarriers = False\n"
        << "d3d11.samplerAnisotropy = 8\n"
        << "d3d11.zeroWorkgroupMemory = False\n"
        << "d3d11.maxFrameLatency = 1\n"
        << "dxgi.maxFrameRate = " << fps << "\n"
        << "dxgi.syncInterval = 1\n"
        << "dxvk.tearFree = True\n";
    if (p.enable_hud) {
        out << "dxvk.hud = fps,frametimes,gpuload,pipelines\n";
    }
    return out.str();
}

inline bool write_dxvk_conf(const std::string& path, const DxvkProfileParams& p) {
    std::ofstream f(path, std::ios::trunc);
    if (!f) return false;
    f << render_dxvk_conf(p);
    return f.good();
}

} // namespace mobiro::gfx
